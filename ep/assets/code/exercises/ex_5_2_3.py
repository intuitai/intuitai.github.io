"""Exercise 5.2.3 — Rounding a price

Chapter 5: Data Structures — Everyday Programming

A price of 3.14159 dollars should be rounded to 2 decimal places,
printing 3.14.

This program contains exactly one bug. Solution: sol_5_2_3.py
"""

price = 3.14159
rounded = round(price)
print(rounded)   # 3.14
